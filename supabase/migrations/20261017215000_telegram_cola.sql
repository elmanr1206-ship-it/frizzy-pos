-- Cola de envíos a Telegram con reintentos (exportada de la base real). Va antes de 20261017220000.
create schema if not exists private;

create table if not exists private.telegram_outbox (
    id bigint generated by default as identity primary key,
    chat_id text not null,
    texto text not null,
    request_id bigint,
    intentos integer not null default 0,
    creado timestamptz not null default now()
);
alter table private.telegram_outbox enable row level security;

create or replace function private.telegram_enviar(p_chat text, p_texto text)
returns void language plpgsql security definer set search_path to 'pg_catalog', 'public', 'pg_temp'
as $function$
declare v_token text; v_id bigint;
begin
  select trim(decrypted_secret) into v_token from vault.decrypted_secrets where name = 'telegram_token' limit 1;
  if v_token is null then
    select trim(valor) into v_token from public.configuracion_sistema where clave = 'telegram_token';
  end if;
  if v_token is null or v_token = '' then return; end if;
  insert into private.telegram_outbox (chat_id, texto, intentos) values (p_chat, p_texto, 1) returning id into v_id;
  update private.telegram_outbox set request_id = net.http_post(
    url := 'https://api.telegram.org/bot' || v_token || '/sendMessage',
    headers := jsonb_build_object('Content-Type', 'application/json'),
    body := jsonb_build_object('chat_id', chat_id, 'text', texto, 'parse_mode', 'HTML'),
    timeout_milliseconds := 8000)
  where id = v_id;
end $function$;

create or replace function private.telegram_reintentar()
returns void language plpgsql security definer set search_path to 'pg_catalog', 'public', 'pg_temp'
as $function$
declare v_token text;
begin
  delete from private.telegram_outbox where creado < now() - interval '2 hours';
  -- entregado (200) o rechazo permanente de Telegram (4xx salvo 429): no se reintenta
  delete from private.telegram_outbox o using net._http_response h
  where h.id = o.request_id
    and (h.status_code = 200 or (h.status_code between 400 and 499 and h.status_code <> 429));
  -- ya falló 6 veces
  delete from private.telegram_outbox o using net._http_response h
  where h.id = o.request_id and o.intentos >= 6;

  select trim(decrypted_secret) into v_token from vault.decrypted_secrets where name = 'telegram_token' limit 1;
  if v_token is null then
    select trim(valor) into v_token from public.configuracion_sistema where clave = 'telegram_token';
  end if;
  if v_token is null or v_token = '' then return; end if;

  -- lo que queda con respuesta fallida (timeout, 5xx, 429) se reenvía
  update private.telegram_outbox o set
    intentos = o.intentos + 1,
    request_id = net.http_post(
      url := 'https://api.telegram.org/bot' || v_token || '/sendMessage',
      headers := jsonb_build_object('Content-Type', 'application/json'),
      body := jsonb_build_object('chat_id', o.chat_id, 'text', o.texto, 'parse_mode', 'HTML'),
      timeout_milliseconds := 8000)
  from net._http_response h
  where h.id = o.request_id;
end $function$;

select cron.schedule('telegram-reintentos', '* * * * *', 'select private.telegram_reintentar()')
where not exists (select 1 from cron.job where jobname = 'telegram-reintentos');
